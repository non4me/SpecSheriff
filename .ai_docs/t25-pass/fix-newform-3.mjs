const present = {};
(function walk(ns) {
  for (const n of ns) {
    present[n.location.replace("_guidelines/spec/", "")] = n;
    if (n.children) walk(n.children);
  }
})(spec.nodes);

const paras = s => s.split("\n\n");
const T = (l, ...i) => i.map(k => paras(present[l].text)[k - 1]).join("\n\n");
const R = (l, ...i) => i.map(k => paras(present[l].reason)[k - 1]).join("\n\n");
const sentences = p => p.split(/(?<=\.) (?=[A-Z])/);
const S = (l, field, p, ...i) => i.map(k => sentences(paras(present[l][field])[p - 1])[k - 1]).join(" ");
const rep = (s, a, b) => {
  if (!s.includes(a)) throw new Error(`not found: ${a}`);
  return s.replace(a, b);
};

